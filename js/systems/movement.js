// ---------------- 运行时 ----------------

// 查某 NPC 某年的所在城
export function cityAt(def, year) {
  const moves = HISTORY_MOVES[def.id];
  if (!moves?.length) return def.city;
  let city = def.city;
  for (const [y, c] of moves) {
    if (year >= y) city = c; else break;
  }
  return city;
}

